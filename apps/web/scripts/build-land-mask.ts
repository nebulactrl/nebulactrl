/**
 * Rasterises Natural Earth 1:50m land (public domain) into a compact
 * equirectangular bitmap and writes it to
 * packages/dither/src/components/backgrounds/data/world-land.ts.
 *
 *   bun run scripts/build-land-mask.ts [--cell 0.5] [--src <geojson url or path>]
 *
 * The bitmap is stored as run-length encoded varints (alternating sea/land
 * runs, sea first, row-major, north row first) wrapped in base64. The
 * decoder lives in data/land-mask.ts. Nothing is fetched at runtime; this
 * script only runs when the mask is regenerated.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const DEFAULT_SRC =
	"https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson";

type Ring = [number, number][];
type Geometry =
	| { type: "Polygon"; coordinates: Ring[] }
	| { type: "MultiPolygon"; coordinates: Ring[][] };

function arg(name: string, fallback: string): string {
	const i = process.argv.indexOf(`--${name}`);
	return i >= 0 && process.argv[i + 1]
		? (process.argv[i + 1] as string)
		: fallback;
}

const cellDeg = Number(arg("cell", "0.5"));
const src = arg("src", DEFAULT_SRC);
const W = Math.round(360 / cellDeg);
const H = Math.round(180 / cellDeg);
const SS = 2; // supersamples per cell axis
const SW = W * SS;
const SH = H * SS;

const text = src.startsWith("http")
	? await (await fetch(src)).text()
	: await Bun.file(src).text();
const geo = JSON.parse(text) as {
	features: { geometry: Geometry }[];
};

// Bucket every polygon edge by the supersample rows it crosses.
const rows: number[][] = Array.from({ length: SH }, () => []);
const xToS = (lon: number) => ((lon + 180) / 360) * SW;
const yToS = (lat: number) => ((90 - lat) / 180) * SH;

function addRing(ring: Ring) {
	for (let i = 0; i < ring.length - 1; i++) {
		const [lon0, lat0] = ring[i] as [number, number];
		const [lon1, lat1] = ring[i + 1] as [number, number];
		let x0 = xToS(lon0);
		let y0 = yToS(lat0);
		let x1 = xToS(lon1);
		let y1 = yToS(lat1);
		if (y0 === y1) continue;
		if (y0 > y1) {
			[x0, x1] = [x1, x0];
			[y0, y1] = [y1, y0];
		}
		// Sample rows sit at j + 0.5.
		const j0 = Math.max(0, Math.ceil(y0 - 0.5));
		const j1 = Math.min(SH - 1, Math.ceil(y1 - 0.5) - 1);
		const slope = (x1 - x0) / (y1 - y0);
		for (let j = j0; j <= j1; j++) {
			(rows[j] as number[]).push(x0 + (j + 0.5 - y0) * slope);
		}
	}
}

for (const f of geo.features) {
	const g = f.geometry;
	const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
	for (const poly of polys) for (const ring of poly) addRing(ring);
}

const hi = new Uint8Array(SW * SH);
for (let j = 0; j < SH; j++) {
	const xs = (rows[j] as number[]).sort((a, b) => a - b);
	for (let k = 0; k + 1 < xs.length; k += 2) {
		const a = Math.max(0, Math.ceil((xs[k] as number) - 0.5));
		const b = Math.min(SW - 1, Math.ceil((xs[k + 1] as number) - 0.5) - 1);
		for (let i = a; i <= b; i++) hi[j * SW + i] = 1;
	}
}

const bits = new Uint8Array(W * H);
for (let y = 0; y < H; y++) {
	for (let x = 0; x < W; x++) {
		let n = 0;
		for (let sy = 0; sy < SS; sy++) {
			for (let sx = 0; sx < SS; sx++) {
				n += hi[(y * SS + sy) * SW + x * SS + sx] as number;
			}
		}
		bits[y * W + x] = n * 2 >= SS * SS ? 1 : 0;
	}
}

const bytes: number[] = [];
const varint = (n: number) => {
	let v = n;
	while (v >= 0x80) {
		bytes.push((v & 0x7f) | 0x80);
		v >>>= 7;
	}
	bytes.push(v);
};
varint(W);
varint(H);
let cur = 0;
let run = 0;
for (let i = 0; i < bits.length; i++) {
	if (bits[i] === cur) {
		run++;
	} else {
		varint(run);
		cur = cur ? 0 : 1;
		run = 1;
	}
}
varint(run);

const b64 = Buffer.from(bytes).toString("base64");
let land = 0;
for (const b of bits) land += b;

const out = `// Generated by scripts/build-land-mask.ts. Do not edit.
// Natural Earth 1:50m land (public domain), ${cellDeg}° cells, ${W}x${H}.
// Run-length varints (sea first, row-major, north row first), base64.
export const WORLD_LAND_WIDTH = ${W};
export const WORLD_LAND_HEIGHT = ${H};
export const WORLD_LAND_RLE =
	"${b64}";
`;

const target = resolve(
	import.meta.dir,
	"../../../packages/dither/src/components/backgrounds/data/world-land.ts",
);
writeFileSync(target, out);
console.log(
	`${W}x${H}, ${bytes.length} RLE bytes, ${b64.length} base64 chars, land ${((land / bits.length) * 100).toFixed(1)}%`,
);
