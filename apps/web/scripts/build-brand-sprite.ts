/**
 * Compiles an allowlist of brand marks from `simple-icons` (a build-time
 * devDependency, CC0-1.0) into two committed files, so the app ships no
 * runtime icon dependency and makes no CDN request:
 *
 *   src/assets/brand-sprite.svg  <symbol id="brand-<slug>"> per mark (fill: currentColor)
 *   src/assets/brand-icons.ts    typed slug list + brand hex + tile/glyph colours
 *
 * The allowlist is the list below plus the `icon:` slug of every template in
 * templates/catalog, so a new template's logo appears after `bun run sprite`.
 * Run with `bun run sprite`. Slugs missing from the installed simple-icons
 * (a template falls back to a tile with its initial) are reported and
 * skipped, never faked.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as simpleIcons from "simple-icons";

/** simple-icons slugs. Aliases (postgres, mongo, node...) live in service-icon.tsx. */
const ALLOWLIST = [
	// databases and stores
	"postgresql",
	"redis",
	"mysql",
	"mariadb",
	"mongodb",
	"elasticsearch",
	"clickhouse",
	"meilisearch",
	"minio",
	// servers, proxies, brokers, observability
	"nginx",
	"traefikproxy",
	"caddy",
	"rabbitmq",
	"apachekafka",
	"grafana",
	"prometheus",
	// runtimes and languages
	"nodedotjs",
	"bun",
	"deno",
	"python",
	"go",
	"rust",
	"php",
	"ruby",
	"openjdk",
	"dotnet",
	// frameworks
	"nextdotjs",
	"nuxt",
	"svelte",
	"astro",
	"react",
	"vuedotjs",
	"angular",
	"django",
	"rubyonrails",
	"laravel",
	"fastapi",
	"express",
	// sources and tooling
	"github",
	"gitlab",
	"bitbucket",
	"docker",
	// notification channels (Slack is not in simple-icons any more)
	"discord",
	"telegram",
] as const;

interface Mark {
	title: string;
	slug: string;
	hex: string;
	path: string;
}

const bySlug = new Map<string, Mark>();
for (const value of Object.values(simpleIcons)) {
	const mark = value as Partial<Mark>;
	if (mark && typeof mark === "object" && mark.slug && mark.path && mark.hex) {
		bySlug.set(mark.slug, mark as Mark);
	}
}

/** WCAG relative luminance of an sRGB hex colour. */
function luminance(hex: string): number {
	const channel = (offset: number) => {
		const value = Number.parseInt(hex.slice(offset, offset + 2), 16) / 255;
		return value <= 0.03928 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
	};
	return 0.2126 * channel(0) + 0.7152 * channel(2) + 0.0722 * channel(4);
}

// Each mark sits on a glossy tile in its own brand colour. Near-black brands
// (GitHub, Bun, Next.js...) would vanish on a dark UI, so they get a slate tile;
// the glyph is white unless that falls under 3:1 against the tile.
const SLATE_TILE = "#4b5565";
const MIN_TILE_LUMINANCE = 0.03;
// A glyph is a graphic, so 3:1 (WCAG 1.4.11) is enough; white is preferred when it reaches it.
const MIN_GLYPH_CONTRAST = 3;
const WHITE_GLYPH = "#ffffff";
const DARK_GLYPH = "#0b0e15";

function contrast(a: number, b: number): number {
	const [hi, lo] = a > b ? [a, b] : [b, a];
	return (hi + 0.05) / (lo + 0.05);
}

/** The `icon: <slug>` of every template in the catalog. */
function catalogIcons(): string[] {
	const dir = join(
		dirname(fileURLToPath(import.meta.url)),
		"..",
		"..",
		"..",
		"templates",
		"catalog",
	);
	const slugs = new Set<string>();
	for (const file of readdirSync(dir)) {
		if (!file.endsWith(".yaml")) continue;
		const match = /^icon:\s*([a-z0-9]+)\s*(?:#.*)?$/m.exec(
			readFileSync(join(dir, file), "utf8"),
		);
		if (match?.[1]) slugs.add(match[1]);
	}
	return [...slugs].sort();
}

const wanted = [...new Set<string>([...ALLOWLIST, ...catalogIcons()])];
const missing: string[] = [];
const found: Mark[] = [];
for (const slug of wanted) {
	const mark = bySlug.get(slug);
	if (mark) found.push(mark);
	else missing.push(slug);
}

const symbols = found
	.map(
		(mark) =>
			`<symbol id="brand-${mark.slug}" viewBox="0 0 24 24"><title>${mark.title}</title><path d="${mark.path}"/></symbol>`,
	)
	.join("\n");
const sprite = `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true">\n${symbols}\n</svg>\n`;

const entries = found
	.map((mark) => {
		const hex = `#${mark.hex.toLowerCase()}`;
		const tile = luminance(mark.hex) < MIN_TILE_LUMINANCE ? SLATE_TILE : hex;
		const tileLuminance = luminance(tile.slice(1));
		const glyph =
			contrast(tileLuminance, 1) >= MIN_GLYPH_CONTRAST
				? WHITE_GLYPH
				: DARK_GLYPH;
		return `\t${JSON.stringify(mark.slug)}: { title: ${JSON.stringify(mark.title)}, hex: ${JSON.stringify(hex)}, tile: ${JSON.stringify(tile)}, glyph: ${JSON.stringify(glyph)} },`;
	})
	.join("\n");

const icons = `// Generated by scripts/build-brand-sprite.ts (\`bun run sprite\`); do not edit.
// Brand marks are from simple-icons (CC0-1.0). The logos are trademarks of their owners, shown only to identify the software a service runs; no endorsement is implied.
export const BRAND_SLUGS = ${JSON.stringify(found.map((m) => m.slug))} as const;

export type BrandSlug = (typeof BRAND_SLUGS)[number];

export interface BrandIcon {
	title: string;
	/** The brand's own colour. */
	hex: string;
	/** Tile fill: the brand colour, or slate when the brand is near-black. */
	tile: string;
	/** Glyph colour on that tile, chosen for contrast. */
	glyph: string;
}

export const BRAND_ICONS: Record<BrandSlug, BrandIcon> = {
${entries}
};

export function isBrandSlug(slug: string): slug is BrandSlug {
	return Object.hasOwn(BRAND_ICONS, slug);
}
`;

const assets = join(
	dirname(fileURLToPath(import.meta.url)),
	"..",
	"src",
	"assets",
);
mkdirSync(assets, { recursive: true });
writeFileSync(join(assets, "brand-sprite.svg"), sprite);
writeFileSync(join(assets, "brand-icons.ts"), icons);

console.log(`brand sprite: ${found.length}/${wanted.length} marks`);
if (missing.length > 0) {
	console.warn(`skipped (not in simple-icons): ${missing.join(", ")}`);
}
