/**
 * Runs after `openapi-ts` (see the `gen:api` script).
 *
 * Writes src/test/api-routes.gen.ts: one "METHOD /path" string type per
 * operation of openapi/openapi.json (paths below /api/v1, every `{param}`
 * written as a `${string}` template hole, so a test may name the segment
 * `:id` or a concrete id). stubApi takes its route keys from that union, so a
 * typo in the method or in a static segment, or a removed endpoint, fails the
 * type check instead of silently stubbing a route the app never calls.
 *
 * Also writes src/test/api-schemas.gen.ts: the schema name -> generated client
 * type map the test factories (src/test/factories.ts) are typed with.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SPEC = join(import.meta.dir, "../../../openapi/openapi.json");
const OUT = join(import.meta.dir, "../src/test/api-routes.gen.ts");
const SCHEMAS_OUT = join(import.meta.dir, "../src/test/api-schemas.gen.ts");
const TYPES = join(import.meta.dir, "../src/api/gen/types.gen.ts");
const METHODS = ["get", "put", "post", "delete", "options", "head", "patch"];

const spec = JSON.parse(readFileSync(SPEC, "utf8")) as {
	paths: Record<string, Record<string, unknown>>;
	components: { schemas: Record<string, unknown> };
};

const keys: string[] = [];
for (const [path, item] of Object.entries(spec.paths)) {
	for (const method of METHODS) {
		if (item[method] === undefined) continue;
		keys.push(
			`${method.toUpperCase()} ${path.replace(/\{[^}]+\}/g, `\${string}`)}`,
		);
	}
}
keys.sort();

const body = keys.map((key) => `\t| \`${key}\``).join("\n");
writeFileSync(
	OUT,
	`// Generated by scripts/gen-api-routes.ts from openapi/openapi.json (bun run gen:api). Do not edit.

/** Every operation of the API: "METHOD /path", the path below /api/v1. */
export type ApiRouteKey =
${body};
`,
);
console.log(
	`wrote ${keys.length} API route keys to src/test/api-routes.gen.ts`,
);

// openapi-ts spells acronyms as words (schema "DNSStatus" is the type `DnsStatus`),
// so a schema maps to the exported type of the same name up to case.
const exported = new Map<string, string>();
for (const match of readFileSync(TYPES, "utf8").matchAll(
	/^export type (\w+) =/gm,
)) {
	const name = match[1] ?? "";
	exported.set(name.toLowerCase(), name);
}
const names = Object.keys(spec.components.schemas).sort();
const lines = names.map((name) => {
	const type = exported.get(name.toLowerCase());
	if (type === undefined) {
		throw new Error(`schema ${name} has no exported type in ${TYPES}`);
	}
	return `\t${JSON.stringify(name)}: T.${type};`;
});
writeFileSync(
	SCHEMAS_OUT,
	`// Generated by scripts/gen-api-routes.ts from openapi/openapi.json (bun run gen:api). Do not edit.
import type * as T from "#/api/gen/types.gen";

/** Every named schema of the API with the generated client type that describes it. */
export interface ApiSchemas {
${lines.join("\n")}
}
`,
);
console.log(`wrote ${names.length} API schemas to src/test/api-schemas.gen.ts`);
