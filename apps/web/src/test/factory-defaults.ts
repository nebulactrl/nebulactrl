/**
 * The deliberate defaults of the schemas tests use most, in one place. A
 * default here is layered over the structural one src/test/factories.ts
 * generates from the spec (required members, the smallest legal value), so a
 * table entry names only the members whose value is a choice; the entry is
 * typed against the generated client type, so a renamed member or a value the
 * type forbids fails the type check, and one the schema forbids fails
 * factories.test.ts.
 *
 * The scene every default describes, so fixtures that meet agree with each
 * other: user "Ada" (not an instance admin) of one team, one project "Shop"
 * with its production environment, in it one running image service "web" that
 * ran its latest deployment successfully on the online server "node-1". Ids are
 * the stable uuids of `IDS`, every date is `EPOCH` (2026-01-15T09:00:00Z) or a
 * day after it. The table counts the schemas the tests' stubApi replies name
 * most (MeBody, Server/PageServer, Project/PageProject, ServiceView,
 * Environment, DomainView ...).
 */
