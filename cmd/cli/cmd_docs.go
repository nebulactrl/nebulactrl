package main

import (
	"fmt"
	"io"
	"os"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// newDocsCmd is the hidden generator behind docs/reference/cli.md. `make
// generate` runs it; the file is committed and compiled into the in-app docs
// by the web build. The tree is walked here rather than through
// github.com/spf13/cobra/doc because that package pulls in go-md2man for man
// pages, a module this repository does not otherwise depend on.
func newDocsCmd(c *cli) *cobra.Command {
	var outFile string
	cmd := &cobra.Command{
		Use:    "docs",
		Short:  "Write the CLI reference as markdown",
		Hidden: true,
		Args:   cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			var w io.Writer = c.out
			if outFile != "" {
				f, err := os.Create(outFile)
				if err != nil {
					return err
				}
				defer f.Close()
				w = f
			}
			return writeCLIReference(w, cmd.Root())
		},
	}
	cmd.Flags().StringVar(&outFile, "out", "", "write to this file instead of stdout")
	return cmd
}

const cliDocsHeader = `---
title: CLI reference
description: Every nebulactrl command, argument and flag, generated from the command tree.
section: Reference
order: 10
generated: true
---

<!-- Generated by ` + "`go run ./cmd/cli docs --out docs/reference/cli.md`" + ` (make generate). Do not edit by hand. -->

# CLI reference

`

func writeCLIReference(w io.Writer, root *cobra.Command) error {
	var b strings.Builder
	b.WriteString(cliDocsHeader)
	b.WriteString("`nebulactrl` is a command line client for the control plane REST API. ")
	b.WriteString("It authenticates with an API token; see [API tokens and scopes](../operations/teams.md) and [the API reference](api.md).\n\n")
	b.WriteString("## Global options\n\n")
	b.WriteString(strings.TrimSpace(root.Long) + "\n\n")
	writeFlagTable(&b, root.PersistentFlags())
	b.WriteString("Exit codes: `0` success, `1` failure, `2` wrong flags or arguments.\n\n")
	b.WriteString("## Command list\n\n")
	b.WriteString("| Command | Description |\n|---|---|\n")
	walkCLI(root, func(cmd *cobra.Command) {
		if cmd == root {
			return
		}
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s |\n", cmd.CommandPath(), cliSlug(cmd.CommandPath()), escapeCell(cmd.Short))
	})
	b.WriteString("\n")
	walkCLI(root, func(cmd *cobra.Command) {
		if cmd == root {
			return
		}
		depth := strings.Count(cmd.CommandPath(), " ")
		level := min(depth+1, 4)
		fmt.Fprintf(&b, "%s %s\n\n", strings.Repeat("#", level), cmd.CommandPath())
		if cmd.Short != "" {
			b.WriteString(cmd.Short + ".\n\n")
		}
		fmt.Fprintf(&b, "```\n%s\n```\n\n", cmd.UseLine())
		if long := strings.TrimSpace(cmd.Long); long != "" && long != cmd.Short {
			b.WriteString(long + "\n\n")
		}
		if cmd.Example != "" {
			fmt.Fprintf(&b, "Examples:\n\n```sh\n%s\n```\n\n", strings.TrimSpace(cmd.Example))
		}
		if cmd.LocalNonPersistentFlags().HasAvailableFlags() {
			b.WriteString("Options:\n\n")
			writeFlagTable(&b, cmd.LocalNonPersistentFlags())
		}
	})
	_, err := io.WriteString(w, b.String())
	return err
}

// walkCLI visits cmd and its visible descendants depth first, in name order.
func walkCLI(cmd *cobra.Command, visit func(*cobra.Command)) {
	visit(cmd)
	subs := append([]*cobra.Command(nil), cmd.Commands()...)
	sort.Slice(subs, func(i, j int) bool { return subs[i].Name() < subs[j].Name() })
	for _, sub := range subs {
		if sub.Hidden || sub.Name() == "help" || sub.Name() == "completion" {
			continue
		}
		walkCLI(sub, visit)
	}
}

func writeFlagTable(b *strings.Builder, fs *pflag.FlagSet) {
	if !fs.HasAvailableFlags() {
		return
	}
	b.WriteString("| Flag | Type | Default | Description |\n|---|---|---|---|\n")
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden {
			return
		}
		name := "--" + f.Name
		if f.Shorthand != "" {
			name = "-" + f.Shorthand + ", " + name
		}
		def := ""
		if f.DefValue != "" && f.DefValue != "false" && f.DefValue != "[]" && f.DefValue != "0" {
			def = "`" + f.DefValue + "`"
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", name, f.Value.Type(), def, escapeCell(f.Usage))
	})
	b.WriteString("\n")
}

func escapeCell(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ").Replace(s)
}

// cliSlug mirrors the web docs heading slugger for a command path.
func cliSlug(path string) string {
	return strings.ReplaceAll(strings.ToLower(path), " ", "-")
}
