package main

import (
	"bytes"
	"fmt"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

// render writes a draft as YAML. REVIEW notes become line comments on the
// matching key; the document starts with a DRAFT banner.
func render(d *draft, src *source) ([]byte, error) {
	var n yaml.Node
	if err := n.Encode(d.T); err != nil {
		return nil, err
	}
	n.HeadComment = fmt.Sprintf("# DRAFT generated by tools/template-translate from %s %s@%s.\n"+
		"# Unfinished: resolve every `# REVIEW:` comment, run tools/template-pin, then move the file to templates/catalog.",
		src.Kind, src.Path, src.Commit)
	used := map[string]bool{}
	decorate(&n, "", d.Reviews, used)
	var extra []string
	for p, msgs := range d.Reviews {
		if !used[p] {
			extra = append(extra, fmt.Sprintf("# REVIEW (%s): %s", p, strings.Join(msgs, "; ")))
		}
	}
	sort.Strings(extra)
	if len(extra) > 0 {
		n.HeadComment += "\n" + strings.Join(extra, "\n")
	}
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(&n); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func join(path, k string) string {
	if path == "" {
		return k
	}
	return path + "." + k
}

func reviewComment(msgs []string) string {
	return "# REVIEW: " + strings.Join(msgs, "; ")
}

// seqItemID names a sequence item for the path (key, name or path field).
func seqItemID(item *yaml.Node) (id string, idValue *yaml.Node) {
	if item.Kind != yaml.MappingNode {
		return "", nil
	}
	for _, field := range []string{"key", "name", "path"} {
		for i := 0; i+1 < len(item.Content); i += 2 {
			if item.Content[i].Value == field {
				return item.Content[i+1].Value, item.Content[i+1]
			}
		}
	}
	return "", nil
}

func attach(key, val *yaml.Node, msgs []string) {
	c := reviewComment(msgs)
	// comments after block collections/multi-line scalars belong on the key
	if val.Kind == yaml.ScalarNode && val.Style&(yaml.LiteralStyle|yaml.FoldedStyle) == 0 && !strings.Contains(val.Value, "\n") {
		val.LineComment = c
		return
	}
	key.LineComment = c
}

func decorate(n *yaml.Node, path string, reviews map[string][]string, used map[string]bool) {
	switch n.Kind {
	case yaml.DocumentNode:
		for _, c := range n.Content {
			decorate(c, path, reviews, used)
		}
	case yaml.MappingNode:
		for i := 0; i+1 < len(n.Content); i += 2 {
			k, v := n.Content[i], n.Content[i+1]
			p := join(path, k.Value)
			if msgs := reviews[p]; len(msgs) > 0 {
				attach(k, v, msgs)
				used[p] = true
			}
			decorate(v, p, reviews, used)
		}
	case yaml.SequenceNode:
		scalars := true
		for _, it := range n.Content {
			if it.Kind != yaml.ScalarNode {
				scalars = false
			}
		}
		if scalars && len(n.Content) > 0 {
			n.Style |= yaml.FlowStyle
			return
		}
		for i, it := range n.Content {
			id, idNode := seqItemID(it)
			if id == "" {
				id = fmt.Sprint(i)
			}
			p := join(path, id)
			if msgs := reviews[p]; len(msgs) > 0 && idNode != nil {
				idNode.LineComment = reviewComment(msgs)
				used[p] = true
			}
			decorate(it, p, reviews, used)
		}
	}
}
